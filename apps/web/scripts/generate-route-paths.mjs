import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const appDir = path.join(root, "src", "app");
const outFile = path.join(root, "src", "lib", "route-paths.ts");

function walk(dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const pages = [];

  for (const entry of entries) {
    const full = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      pages.push(...walk(full));
    } else if (entry.name === "page.tsx") {
      pages.push(full);
    }
  }

  return pages;
}

const paths = walk(appDir)
  .map((file) => {
    const rel = path.relative(appDir, file).replace(/[\\/]page\.tsx$/, "");
    const normalized = rel
      .split(path.sep)
      .filter(Boolean)
      .map((segment) => (/^\[.*\]$/.test(segment) ? "_" : segment))
      .join("/");

    return `/${normalized}`.replace(/\/$/, "") || "/";
  })
  .filter((value, index, all) => all.indexOf(value) === index)
  .sort();

const body = `// AUTO-GENERATED by scripts/generate-route-paths.mjs - do not edit by hand.
// Every page path in src/app, with dynamic segments ([id], ...) replaced by "_".
// Used by lib/breadcrumbs.ts to avoid linking to non-existent placeholder routes.
export const ROUTE_PATHS: readonly string[] = ${JSON.stringify(paths, null, 2)};
`;

fs.writeFileSync(outFile, body);
console.log(`Wrote ${paths.length} route paths to ${path.relative(root, outFile)}`);
